// Run: node scripts/passage_rules.test.mjs
import assert from 'node:assert/strict';
import fs from 'node:fs';
const source=fs.readFileSync(new URL('../js/passage-rules.js',import.meta.url),'utf8');
const {vocabularyIndex,passageTiers,tierCoverage}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const lower=['我','你','他','她','是','的','在','家','书','看'];
const own=['考试','教室','告诉','准备','题','开始','完','错','不错','记得','运动'];
const vocab=[...lower.map(h=>({h,l:1})),...own.map(h=>({h,l:2})),{h:'高级',l:3}];
const ix=vocabularyIndex(vocab);
const targets=own.slice(0,10);
const tokens=[...targets,...Array(70).fill('我')];
const q={passageLevel:2,sublevel:'learner',passageTokens:tokens,words:targets};
assert.deepEqual(passageTiers([q],ix).tracks,['learner']);
assert.equal(passageTiers([{...q,passageTokens:[...tokens,'运动']}],ix),null,'unlisted same-level word rejected');
assert.equal(passageTiers([{...q,passageTokens:[...tokens,'高级']}],ix),null,'higher-level word rejected');
assert.equal(passageTiers([{...q,words:targets.slice(0,9)}],ix),null,'nine targets rejected');
assert.equal(passageTiers([{...q,words:[...targets.slice(0,9),'我']}],ix),null,'lower-level target rejected');
const challenge=passageTiers([{...q,sublevel:'challenge',words:[...targets,'运动'],passageTokens:[...tokens,'运动']}],ix);
assert.equal(challenge.challengeTargets.length,11,'challenge has no fixed target count');
assert.equal(passageTiers([{...q,passageLevel:1,passageTokens:lower,words:lower}],ix).learnerTargets.length,10,'HSK 1 short dialogue');
const make=(id,body)=>({id,level:2,body,tokens,tracks:['learner'],learnerTargets:targets});
const ch={id:'c',level:2,body:'挑战',tokens:[...tokens,'运动'],tracks:['challenge'],learnerTargets:[]};
let stats=tierCoverage([make('a','一'),make('b','二'),make('c','二'),ch],vocab)[1];
assert.equal(stats.learner.covered,0,'duplicate text must not count as a third context');
assert.equal(stats.challenge.covered,11,'challenge coverage independent');
stats=tierCoverage([make('a','一'),make('b','二'),make('c','三'),ch],vocab)[1];
assert.equal(stats.learner.covered,10,'three distinct passages count');
assert.equal(stats.learner.remaining,1,'uncovered target remains');
console.log('Passage rule regression tests passed.');
